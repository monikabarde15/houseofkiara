export const SKU_PREFIX = "HOK-SKU-";
export const AUTO_SKU_REGEX = /^HOK-SKU-(\d+)$/i;

export function formatSku(num) {
  const n = Math.max(1, Math.floor(Number(num) || 1));
  return `${SKU_PREFIX}${String(n).padStart(4, "0")}`;
}

export function computeNextSkuFromList(
  existingSkus = [],
  { afterSku = "" } = {},
) {
  const existingSet = new Set();
  let maxNum = 0;

  const candidates = afterSku ? [...existingSkus, afterSku] : existingSkus;

  for (const raw of candidates) {
    const trimmed = String(raw || "").trim();
    if (!trimmed) continue;
    existingSet.add(trimmed.toUpperCase());

    const match = trimmed.match(AUTO_SKU_REGEX);
    if (match) {
      const parsed = Number.parseInt(match[1], 10);
      if (Number.isFinite(parsed) && parsed > maxNum) {
        maxNum = parsed;
      }
    }
  }

  let nextNum = maxNum + 1;
  let candidate = formatSku(nextNum);
  while (existingSet.has(candidate.toUpperCase())) {
    nextNum += 1;
    candidate = formatSku(nextNum);
  }

  return candidate;
}

const isSameDoc = (doc, excludeDoc) => {
  if (!doc || !excludeDoc) return false;
  const docMongoId = doc._id ? String(doc._id) : "";
  const exclMongoId = excludeDoc._id ? String(excludeDoc._id) : "";
  if (docMongoId && exclMongoId && docMongoId === exclMongoId) return true;

  const docProductId = doc.productId ? String(doc.productId).trim() : "";
  const exclProductId = excludeDoc.productId
    ? String(excludeDoc.productId).trim()
    : "";
  return Boolean(docProductId && exclProductId && docProductId === exclProductId);
};

export async function getAllExistingSkus(ProductModel, excludeDoc = null) {
  const docs = await ProductModel.find({});
  const skus = [];
  for (const doc of docs || []) {
    if (excludeDoc && isSameDoc(doc, excludeDoc)) continue;
    const sku = String(doc?.sku || doc?.data?.sku || "").trim();
    if (sku) skus.push(sku);
  }
  return skus;
}

export async function isSkuTaken(ProductModel, candidateSku, excludeDoc = null) {
  const target = String(candidateSku || "").trim().toUpperCase();
  if (!target) return false;
  const existingSkus = await getAllExistingSkus(ProductModel, excludeDoc);
  return existingSkus.some((s) => s.trim().toUpperCase() === target);
}

export async function resolveUniqueSku(
  ProductModel,
  requestedSku,
  { excludeDoc = null, allowAutoBump = true } = {},
) {
  const trimmed = String(requestedSku || "").trim();
  const otherSkus = await getAllExistingSkus(ProductModel, excludeDoc);
  const takenSet = new Set(otherSkus.map((s) => s.trim().toUpperCase()));

  if (!trimmed) {
    return { sku: computeNextSkuFromList(otherSkus), autoGenerated: true };
  }

  if (!takenSet.has(trimmed.toUpperCase())) {
    return { sku: trimmed, autoGenerated: false };
  }

  if (allowAutoBump && AUTO_SKU_REGEX.test(trimmed)) {
    return { sku: computeNextSkuFromList(otherSkus), autoGenerated: true };
  }

  return {
    error: `SKU "${trimmed}" already exists. Every product must have a unique SKU.`,
  };
}

export async function generateNextUniqueSku(
  ProductModel,
  { afterSku = "" } = {},
) {
  const existingSkus = await getAllExistingSkus(ProductModel);
  return computeNextSkuFromList(existingSkus, { afterSku });
}

let skuQueue = Promise.resolve();

export function withSkuLock(fn) {
  const next = skuQueue.then(fn, fn);
  skuQueue = next.catch(() => {});
  return next;
}
